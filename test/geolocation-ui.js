const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const {spawn} = require('node:child_process');
(async () => {
    const base = process.env.NEXO_TEST_BASE_URL, login = process.env.NEXO_TEST_LOGIN, password = process.env.NEXO_TEST_PASSWORD;
    assert.ok(base && login && password, 'Use the isolated PHP payment proofs test runner.');
    const profile = fs.mkdtempSync(path.join(os.tmpdir(), 'nexo-geo-test-'));
    const child = spawn(process.env.NEXO_CHROME || 'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe', ['--headless=new', '--disable-gpu', '--no-sandbox', '--remote-debugging-port=0', '--no-first-run', '--user-data-dir=' + profile, 'about:blank'], {windowsHide:true, stdio:'ignore'});
    let ws;
    try {
        const portFile = path.join(profile, 'DevToolsActivePort');
        for(let i=0; !fs.existsSync(portFile)&&i<100; i++) await new Promise(resolve=>setTimeout(resolve,100));
        const port=fs.readFileSync(portFile,'utf8').split('\n')[0];
        const target=await(await fetch('http://127.0.0.1:'+port+'/json/new?about:blank',{method:'PUT'})).json();
        ws=new WebSocket(target.webSocketDebuggerUrl);
        await new Promise((resolve,reject)=>{ws.onopen=resolve;ws.onerror=reject;});
        let next=0; const pending=new Map(), errors=[];
        ws.onmessage=event=>{const m=JSON.parse(event.data);if(m.method==='Runtime.exceptionThrown')errors.push(m.params.exceptionDetails.exception?.description||m.params.exceptionDetails.text);if(pending.has(m.id)){const p=pending.get(m.id);clearTimeout(p.timer);pending.delete(m.id);m.error?p.reject(Error(m.error.message)):p.resolve(m.result);}};
        const call=(method,params={})=>new Promise((resolve,reject)=>{const id=++next;const timer=setTimeout(()=>reject(Error('CDP timeout '+method)),10000);pending.set(id,{resolve,reject,timer});ws.send(JSON.stringify({id,method,params}));});
        const evaluate=async expression=>{const r=await call('Runtime.evaluate',{expression,returnByValue:true,awaitPromise:true});if(r.exceptionDetails)throw Error(r.exceptionDetails.exception?.description||r.exceptionDetails.text);return r.result.value;};
        const until=async expression=>{for(let i=0;i<100;i++){try{if(await evaluate(expression))return;}catch{}await new Promise(resolve=>setTimeout(resolve,100));}throw Error('Timed out: '+expression+'; errors: '+errors.join('; '));};
        await call('Runtime.enable'); await call('Page.enable');
        await call('Emulation.setDeviceMetricsOverride',{width:1440,height:1000,deviceScaleFactor:1,mobile:false});


        const contact=process.env.NEXO_GEO_CLIENT;assert.ok(contact);
        await call('Page.navigate',{url:base+'/login.php'});
        await until('!!document.querySelector("[name=login]")');
        await evaluate('document.querySelector("[name=login]").value='+JSON.stringify(login)+';document.querySelector("[name=password]").value='+JSON.stringify(password)+';document.querySelector("form").requestSubmit()');
        await until('!location.pathname.endsWith("/login.php")');
        await call('Page.navigate',{url:base+'/modules/ventas/index.php?new=1'});
        await until('document.readyState==="complete" && !!document.querySelector("[data-geolocation=sale]")');
        await evaluate('window.geoRequests=[];Object.defineProperty(navigator,"geolocation",{configurable:true,value:{getCurrentPosition(success,error,options){geoRequests.push({success,error,options});}}});');
        await evaluate('document.querySelector("[name=customer_id]").value='+JSON.stringify(contact)+';document.querySelector("[name=customer_id]").dispatchEvent(new Event("change",{bubbles:true}));');
        const point=role=>evaluate('(()=>{const p=document.querySelector("[data-geolocation='+role+']");return [...p.querySelectorAll("[data-geo-latitude],[data-geo-longitude]")].map(f=>f.value);})()');
        const capture=role=>evaluate('document.querySelector("[data-geolocation='+role+'] [data-geo-capture]").click()');
        assert.deepEqual(await point('customer'),['12.000000','-68.000000']);
        assert.deepEqual(await point('sale'),['','']);
        assert.equal(await evaluate('geoRequests.length'),0);
        await capture('sale');
        await evaluate('geoRequests.at(-1).success({coords:{latitude:11.888888,longitude:-67.999999,accuracy:15}})');
        assert.deepEqual(await point('sale'),['11.888888','-67.999999']);
        assert.deepEqual(await point('customer'),['12.000000','-68.000000']);
        assert.equal(await evaluate('document.querySelector("[data-geolocation=sale] [data-geo-source]").value'),'device');
        await capture('customer');
        await evaluate('geoRequests.at(-1).success({coords:{latitude:9.999999,longitude:-65.888888,accuracy:10}})');
        assert.deepEqual(await point('customer'),['9.999999','-65.888888']);
        assert.deepEqual(await point('sale'),['11.888888','-67.999999']);
        assert.equal(await evaluate('document.querySelector("[data-geolocation=customer] [data-geo-map]").href.includes("mlon=-65.888888")'),true);
        await capture('sale');await evaluate('geoRequests.at(-1).error({code:1})');
        assert.deepEqual(await point('sale'),['11.888888','-67.999999']);
        assert.equal(await evaluate('document.querySelector("[data-geolocation=sale] [data-geo-status]").textContent.includes("continuar")'),true);
        await evaluate('document.querySelector("[data-geolocation=sale] [data-geo-clear]").click()');
        assert.deepEqual(await point('sale'),['','']);
        assert.deepEqual(await point('customer'),['9.999999','-65.888888']);
        await capture('customer');
        await evaluate('(()=>{const f=document.querySelector("[data-order-address=delivery]");f.value=[...f.options].find(o=>o.textContent==="Principal").value;f.dispatchEvent(new Event("change",{bubbles:true}));geoRequests.at(-1).success({coords:{latitude:1,longitude:2}});})()');
        assert.deepEqual(await point('customer'),['10.480601','-66.903607']);
        assert.deepEqual(await point('sale'),['','']);
        await capture('sale');
        assert.equal(await evaluate('(()=>{const e=new Event("submit",{bubbles:true,cancelable:true});document.querySelector("[data-geolocation=sale]").closest("form").dispatchEvent(e);return e.defaultPrevented;})()'),true);
        await evaluate('geoRequests.at(-1).error({code:3})');
        await call('Emulation.setDeviceMetricsOverride',{width:390,height:844,deviceScaleFactor:1,mobile:true});
        assert.equal(await evaluate('document.documentElement.scrollWidth<=innerWidth+1'),true);
        assert.deepEqual(errors,[]);
        console.log('PASS: browser independent capture, address defaults, optional permission denial, clear, stale GPS callbacks, pending submit and mobile layout.');
        await call('Browser.close');
    } finally {
        ws?.close();child.kill();await new Promise(resolve=>setTimeout(resolve,500));
        if(path.dirname(profile)===path.resolve(os.tmpdir())&&path.basename(profile).startsWith('nexo-geo-test-'))fs.rmSync(profile,{recursive:true,force:true,maxRetries:5,retryDelay:200});
    }
})().catch(error=>{console.error(error);process.exitCode=1;});
